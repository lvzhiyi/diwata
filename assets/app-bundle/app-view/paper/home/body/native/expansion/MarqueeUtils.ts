/**
 * 获取距离当前时间最近的大奖消息
 * @returns 返回距离当前时间最近的大奖消息
 */
export const getNearestMarqueeBigPrize = () => {
  const reg = /\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}/;

  const loginTimestamp = app.manager.global.getLoginTimestamp() || 0;
    
  let index = marqueeBigPrizeList.findIndex(item => {
    const match = item.time.match(reg);

    const textTime = new Date(match[0]).getTime();

    return textTime > loginTimestamp;
  });

  const lastItemTextTime = new Date(marqueeBigPrizeList[marqueeBigPrizeList.length - 1]?.time.match(reg)[0]).getTime();

  // 定义最大允许的时间差2小时
  const MAX_TIME_DIFF_MS = 2 * 60 * 60 * 1000;

  if (loginTimestamp > lastItemTextTime && loginTimestamp - lastItemTextTime < MAX_TIME_DIFF_MS) {
    return marqueeBigPrizeList[marqueeBigPrizeList.length - 1].message;
  } if (index > 0) {
    index = index - 1;

    return marqueeBigPrizeList[index].message;
  } else {
    return null;
  }
};